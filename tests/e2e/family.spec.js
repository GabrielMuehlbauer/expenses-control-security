const { test, expect } = require('@playwright/test');
const crypto = require('node:crypto');
const sharp = require('sharp');
test('responsavel, filho, receitas, saldo e comprovante autorizado', async ({ page }, testInfo) => {
  page.on('dialog', dialog => dialog.accept());
  const run = crypto.randomBytes(6).toString('hex');
  const parentEmail = `parent-browser-${run}@example.com`, childEmail = `child-browser-${run}@example.com`, password = 'FamiliaNavegador!123';
  async function login(email) {
    await page.goto('/login');
    await page.getByLabel('E-mail', { exact: true }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Histórico financeiro' })).toBeVisible();
  }
  await page.goto('/register');
  await page.getByLabel('Nome', { exact: true }).fill('Responsavel navegador');
  await page.getByLabel('E-mail', { exact: true }).fill(parentEmail);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Cadastrar', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/); await login(parentEmail);
  await page.getByRole('button', { name: 'Controle parental', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome do filho').fill('Filho navegador');
  await dialog.getByLabel('E-mail do filho').fill(childEmail);
  await dialog.getByLabel('Senha inicial do filho').fill(password);
  await dialog.getByRole('button', { name: 'Criar conta de filho', exact: true }).click();
  await expect(dialog.getByRole('group', { name: 'Filho navegador' })).toBeVisible();
  await expect(dialog.getByLabel('Visualizar', { exact: true })).toBeChecked();
  await expect(dialog.getByLabel('Editar', { exact: true })).not.toBeChecked();
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByLabel('Conta selecionada').selectOption({ label: 'Filho navegador' });
  await expect(page.getByText('Nenhuma categoria registrada.')).toBeVisible();
  await page.getByRole('button', { name: '+', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome da Categoria:').fill('Categoria familiar');
  await dialog.getByLabel('Descrição da Categoria:').fill('Financas do filho');
  await dialog.getByRole('button', { name: 'Adicionar Categoria' }).click();
  await expect(page.getByRole('button', { name: /^Categoria familiar/ })).toBeVisible();
  async function createEntry(type, title, amount) {
    await page.getByRole('button', { name: `Criar ${type} +`, exact: true }).click();
    const form = page.getByRole('dialog');
    await form.getByLabel(`Título da ${type}:`).fill(title);
    await form.getByLabel(`Data da ${type}:`).fill('2026-01-10');
    await form.getByLabel('Categoria:', { exact: true }).selectOption({ label: 'Categoria familiar' });
    await form.getByLabel('Status:', { exact: true }).selectOption('PAGA');
    await form.getByLabel(`Valor da ${type}:`).fill(amount);
    await form.getByRole('button', { name: `Adicionar ${type}`, exact: true }).click();
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  }
  await createEntry('Receita', 'Mesada recebida', '100.00');
  await createEntry('Despesa', 'Compra do filho', '25.50');
  await expect(page.getByText(/74,50/)).toBeVisible();
  await page.getByRole('heading', { name: 'Compra do filho', exact: true }).click();
  const png = await sharp({ create: { width: 20, height: 20, channels: 3, background: '#abd035' } }).png().toBuffer();
  await page.getByLabel('Arquivo do comprovante').setInputFiles({ name: 'cupom.png', mimeType: 'image/png', buffer: png });
  await expect(page.getByRole('button', { name: 'Baixar comprovante' })).toBeVisible();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Baixar comprovante' }).click();
  expect((await downloaded).suggestedFilename()).toBe('comprovante.png');
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.screenshot({ path: testInfo.outputPath('dashboard-familia.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/); await login(childEmail);
  await expect(page.getByRole('button', { name: 'Criar Despesa +', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Controle parental', exact: true })).toHaveCount(0);
  await expect(page.getByLabel('Conta selecionada')).toHaveCount(0);
  await expect(page.getByText(/74,50/)).toBeVisible();
  await page.getByRole('heading', { name: 'Compra do filho', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Editar', exact: true })).toHaveCount(0);
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true })).toHaveCount(0);
  await expect(page.getByLabel('Arquivo do comprovante')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Baixar comprovante' })).toBeVisible();
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/); await login(parentEmail);
  await expect(page.getByText(/74,50/)).toHaveCount(0);
  await page.getByRole('button', { name: 'Controle parental', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Criar lançamentos e categorias', { exact: true }).check();
  await expect(page.getByRole('dialog').getByLabel('Criar lançamentos e categorias', { exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/); await login(childEmail);
  await expect(page.getByRole('button', { name: 'Criar Despesa +', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
});
