const { test, expect } = require('@playwright/test');
const crypto = require('node:crypto');
test('cadastro, login, CRUD, texto seguro, persistencia e logout', async ({ page }) => {
  const email = `browser-${crypto.randomBytes(6).toString('hex')}@example.com`;
  const password = 'NavegadorSeguro!123';
  page.on('dialog', dialog => dialog.accept());
  await page.goto('/register');
  await page.getByLabel('Nome', { exact: true }).fill('Usuario navegador');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Cadastrar', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('senha incorreta');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('invalidos');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Minhas despesas' })).toBeVisible();
  await page.getByRole('button', { name: '+', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome da Categoria:').fill('Categoria navegador');
  await dialog.getByLabel('Descrição da Categoria:').fill('Teste de integracao');
  await dialog.getByRole('button', { name: 'Adicionar Categoria' }).click();
  await expect(page.getByRole('button', { name: /^Categoria navegador/ })).toBeVisible();
  await page.getByRole('button', { name: 'Criar Despesa +' }).click();
  dialog = page.getByRole('dialog');
  const title = '<img src=x onerror=alert(999)> Texto seguro';
  await dialog.getByLabel('Título da Despesa:').fill(title);
  await dialog.getByLabel('Data da Despesa:').fill('2026-01-10');
  await dialog.getByLabel('Descrição da Despesa:').fill('Descricao inicial');
  await dialog.getByLabel('Categoria:', { exact: true }).selectOption({ label: 'Categoria navegador' });
  await dialog.getByLabel('Valor da Despesa:').fill('12.34');
  await dialog.getByRole('button', { name: 'Adicionar Despesa' }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.getByText('10 de janeiro de 2026', { exact: true })).toBeVisible();
  expect(await page.locator('img[onerror]').count()).toBe(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.getByRole('heading', { name: title, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Editar', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Título da Despesa:').fill('Despesa editada');
  await dialog.getByLabel('Descrição da Despesa:').fill('');
  await dialog.getByLabel('Status:').selectOption('PAGA');
  await dialog.getByRole('button', { name: 'Salvar Alterações' }).click();
  await expect(page.getByRole('heading', { name: 'Despesa editada', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^Categoria navegador/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByRole('heading', { name: 'Despesa editada', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Despesa editada', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: /^Categoria navegador/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Categoria navegador/ })).toHaveCount(0);
  const cookies = await page.context().cookies();
  const sessionCookie = cookies.find(cookie => cookie.name === 'ec_session');
  expect(sessionCookie.httpOnly).toBe(true);
  expect(await page.evaluate(() => localStorage.getItem('@ExpensesControl:token'))).toBeNull();
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.reload();
  await expect(page).toHaveURL(/\/login$/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test('falha de dashboard oferece mensagem e nova tentativa', async ({ page }) => {
  page.on('dialog', dialog => dialog.accept());
  const email = `failure-${crypto.randomBytes(6).toString('hex')}@example.com`;
  await page.goto('/register');
  await page.getByLabel('Nome', { exact: true }).fill('Usuario teste');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('NavegadorSeguro!123');
  await page.getByRole('button', { name: 'Cadastrar', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.route('**/api/dashboard/total-expenses', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }));
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('NavegadorSeguro!123');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Não foi possível atualizar');
  await page.unroute('**/api/dashboard/total-expenses');
  await page.getByRole('button', { name: 'Tentar novamente' }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
});
